/**
 * Localizes Matchmaking Overall Recommendation
 */
function getLocalizedMatchmakingRecommendation(gunasObtained, lang = 'en', baseRec = null) {
  if (lang === 'en') return baseRec;
  const content = MATCHMAKING_CONTENT[lang] || MATCHMAKING_CONTENT['hi'] || MATCHMAKING_CONTENT['mr'];

  let verdict = content.favorableVerdict;
  let summaryTemplate = content.favorableSummary;

  if (gunasObtained >= 25) {
    verdict = content.excellentVerdict;
    summaryTemplate = content.excellentSummary;
  } else if (gunasObtained < 18) {
    verdict = content.challengingVerdict;
    summaryTemplate = content.challengingSummary;
  }

  const summary = summaryTemplate.replace('{{score}}', String(gunasObtained));
  const title = OVERALL_RECOMMENDATION_TITLES[lang] || OVERALL_RECOMMENDATION_TITLES['hi'] || 'Overall Recommendation';

  return {
    ...baseRec,
    title,
    verdict,
    summary,
  };
}

/**
 * Localizes Ashtakoota Gunas Descriptions
 */
function getLocalizedKootaDescription(kootaName, lang = 'en', defaultDesc = '') {
  if (lang === 'en') return defaultDesc;
  const content = MATCHMAKING_CONTENT[lang] || MATCHMAKING_CONTENT['hi'] || MATCHMAKING_CONTENT['mr'];
  return content?.kootaDescriptions?.[kootaName] || defaultDesc;
}

