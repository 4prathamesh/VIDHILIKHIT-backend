/**
 * Localizes Tithi strings like "Shukla Dashami"
 */
function localizeTithi(tithiStr, lang = 'en') {
  if (!tithiStr || lang === 'en') return tithiStr;
  const langMap = TITHI_MAP[lang] || TITHI_MAP['hi'];
  if (!langMap) return tithiStr;

  let localized = tithiStr;
  for (const [enKey, locVal] of Object.entries(langMap)) {
    localized = localized.replace(new RegExp(`\\b${enKey}\\b`, 'g'), locVal);
  }
  return localized;
}

